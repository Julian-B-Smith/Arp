#!/usr/bin/env python3
"""gen_bank.py - generate core/include/arp/bank_data.h from spec/bank/starter.json.

    python3 tools/gen_bank.py            write the header
    python3 tools/gen_bank.py --check    exit 1 if the header on disk differs from what the JSON generates

The bank is DATA (SPEC 4.3, D-004): the C++ core embeds it so the core needs no file or parser at run time. The JSON
is normative; the header is generated and never hand-edited. tools/core_params_check.py runs the --check AND compares
the compiled bank (arp_tests --dump-bank) with the JSON, each with a planted control.
Stdlib only.
"""
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BANK_JSON = REPO / "spec" / "bank" / "starter.json"
HEADER = REPO / "core" / "include" / "arp" / "bank_data.h"
PICK_CODES = {"order": 0, "low": 9, "high": 10, "chord": 11}   # 1..8 stay themselves (arp/pattern.h)
MAX_STEPS = 64


def pick_code(v):
    if isinstance(v, int) and not isinstance(v, bool) and 1 <= v <= 8:
        return v
    if isinstance(v, str) and v in PICK_CODES:
        return PICK_CODES[v]
    raise ValueError("bad pick %r" % (v,))


def resolved(bank):
    """The bank as plain data: [(id, length, step_size, unit, [step dict with every field])]."""
    d = bank["step_defaults"]
    pd = bank["pattern_defaults"]
    out = []
    for p in bank["patterns"]:
        n = p["length"]
        if not 1 <= n <= MAX_STEPS or len(p["steps"]) != n:
            raise ValueError("pattern %s: length %s does not match its %d steps" % (p["id"], n, len(p["steps"])))
        steps = []
        for s in p["steps"]:
            f = dict(d)
            f.update(s)
            f["pick"] = pick_code(f["pick"])
            steps.append(f)
        out.append((p["id"], n, p.get("step_size", pd["step_size"]), p.get("step_unit", pd["step_unit"]), steps))
    return out


def generate(bank):
    rows = resolved(bank)
    lines = [
        "// GENERATED by tools/gen_bank.py from spec/bank/starter.json - DO NOT EDIT BY HAND.",
        "// tools/core_params_check.py regenerates it in memory and compares, and compares the compiled bank with the JSON.",
        "#pragma once",
        "",
        '#include "arp/pattern.h"',
        "",
        "namespace arp {",
        "",
        "inline constexpr int kBankCount = %d;" % len(rows),
        "// The pattern ids, in order: they are the first kBankCount values of the `pattern` setting (arp::Pattern).",
        "inline constexpr const char* kBankIds[kBankCount] = {%s};" % ", ".join('"%s"' % r[0] for r in rows),
        "",
        "// {on, tie, vel, gate, step, prob, ratchet, trig, pick}",
        "inline constexpr PatternDef kBank[kBankCount] = {",
    ]
    for pid, n, size, unit, steps in rows:
        lines.append("    {%d, %d, StepUnit::%s, {  // %s" % (n, size, unit.capitalize(), pid))
        for s in steps:
            lines.append("        {%s, %s, %d, %d, %d, %d, %d, %d, %d}," % (
                "true" if s["on"] else "false", "true" if s["tie"] else "false",
                s["vel"], s["gate"], s["step"], s["prob"], s["ratchet"], s["trig"], s["pick"]))
        lines.append("    }},")
    lines += ["};", "", "}  // namespace arp", ""]
    return "\n".join(lines)


def main(argv):
    bank = json.loads(BANK_JSON.read_text())
    text = generate(bank)
    if "--check" in argv:
        have = HEADER.read_text() if HEADER.exists() else ""
        if have != text:
            print("FAIL  %s is not what %s generates; run: python3 tools/gen_bank.py" % (HEADER.relative_to(REPO), BANK_JSON.relative_to(REPO)))
            return 1
        print("PASS  %s equals the generated bank (%d patterns)" % (HEADER.relative_to(REPO), len(bank["patterns"])))
        return 0
    HEADER.write_text(text)
    print("wrote %s (%d patterns)" % (HEADER.relative_to(REPO), len(bank["patterns"])))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
