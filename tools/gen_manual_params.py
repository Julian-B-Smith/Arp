#!/usr/bin/env python3
"""Generate and check the settings reference of the Arp manual page (ROADMAP T-007, M3).

The table between the markers in docs/manual/arp.md is GENERATED from spec/params.json (display name, kind of
control, range or choices, default, unit) and, for the Pattern choices, spec/bank/starter.json. Nothing in it is
typed by hand, so the page cannot disagree with the spec.

  python3 tools/gen_manual_params.py --write   rewrite the table between the markers
  python3 tools/gen_manual_params.py --check   exit 0 if the page equals the generator's output (and the page's
                                               placeholders, status lines, wording and stated numbers pass); else
                                               print why, exit 1
  python3 tools/gen_manual_params.py --plant   the must-fail controls: perturb one thing in memory per detector.
                                               Exit 3 and the line "every plant was detected" = every detector went
                                               red (the controls work). Exit 3 is deliberate: a Python crash exits 1,
                                               so it cannot pass for success. Exit 2 = a detector missed its plant
                                               (or a setup error); anything else = broken.

Exit 2 also means a setup error (a marker is missing, an unmapped unit). Standard library only. Run by
./verify fast (manual_gate): the plants first, then the check.
"""
from __future__ import annotations

import copy
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARAMS = ROOT / "spec" / "params.json"
BANK = ROOT / "spec" / "bank" / "starter.json"
PAGE = ROOT / "docs" / "manual" / "arp.md"
FIGURES = ROOT / "docs" / "manual" / "figures.json"

BEGIN = "<!-- BEGIN GENERATED: params -->"
END = "<!-- END GENERATED: params -->"
STAMP = "<!-- Generated by tools/gen_manual_params.py from spec/params.json and spec/bank/starter.json. Do not edit by hand. -->"

MINUS = "−"
NOTE_NAMES = ["C", "C♯", "D", "D♯", "E", "F", "F♯", "G", "G♯", "A", "A♯", "B"]

# The unit shown in the manual for each raw `unit` in params.json. An unmapped unit is a setup error (exit 2): a new
# kind of unit in the spec must be given a musician's wording here, not slip into the page unreviewed.
UNIT_MAP = {
    "%": "%",
    "passes": "passes",
    "cycles": "cycles",
    "MIDI velocity (1–127)": "MIDI velocity",
    "microseconds per step": "ms (and Hz)",
    "semitones or degrees, per step_unit": "st or scale degrees, per **Step unit**",
    "semitones or degrees, per chord_unit": "st or scale degrees, per **Chord unit**",
}

# horde's manual README, "Figures, tables and audio".
KINDS = {"figure", "diagram", "table", "screenshot", "audio"}
STATUSES = {"needed", "pending-design", "ready-to-make"}
FIELDS = ["id", "kind", "chapter", "purpose", "content", "source", "depends_on", "status", "generated"]
PLACEHOLDER_KINDS = {"FIG": {"figure", "diagram", "screenshot"}, "TAB": {"table"}, "AUD": {"audio"}}
PLACEHOLDER = re.compile(r"^\[\[(FIG|TAB|AUD):([^\]]*)\]\]$")


class SetupError(Exception):
    pass


# ---------------------------------------------------------------- number formatting

def num(v: int, signed: bool = False) -> str:
    if v < 0:
        return f"{MINUS}{-v}"
    return f"+{v}" if signed and v > 0 else str(v)


def trim(x: float) -> str:
    s = f"{x:.3f}".rstrip("0").rstrip(".")
    return s


def time_text(us: int) -> str:
    return f"{trim(us / 1e6)} s" if us >= 1_000_000 else f"{trim(us / 1e3)} ms"


def hz_text(us: int) -> str:
    return f"{trim(1e6 / us)} Hz"


# ---------------------------------------------------------------- the table

def _unit(p: dict) -> str:
    raw = p.get("unit")
    if raw is None:
        return "—"
    if raw not in UNIT_MAP:
        raise SetupError(f"unmapped unit {raw!r} on {p['key']}: give it a wording in UNIT_MAP")
    return UNIT_MAP[raw]


def _name(p: dict) -> str:
    return f"**{p['label']}**"


def _row(p: dict, bank: dict, rates: list) -> list[str]:
    """One ordinary setting: [name, control, range or choices, default, unit, in a morph]."""
    key, typ = p["key"], p["type"]
    morph = "Blends" if p["kind"] == "continuous" else "Switches"
    unit = _unit(p)

    if typ == "bool":
        return [_name(p), "Switch", "On, Off", "On" if p["default"] else "Off", unit, morph]

    if typ == "enum":
        if key == "pattern":
            names = {b["id"]: b["name"] for b in bank["patterns"]}
            choices = ", ".join(b["name"] for b in bank["patterns"]) + ", Build your own"
            default = names[p["default"]]
        elif key == "rate":
            names = {r["name"]: (f"{r['name']} ({r['alias']})" if r["alias"] else r["name"]) for r in rates}
            choices = ", ".join(names[r["name"]] for r in rates)
            default = names[p["default"]]
        else:
            labels = p["value_labels"]
            choices = ", ".join(labels[v] for v in p["values"])
            default = labels[p["default"]]
        return [_name(p), "Choice", choices, default, unit, morph]

    # numbers
    lo, hi, d = p.get("min"), p.get("max"), p["default"]
    if key == "step_time_us":
        rng = f"{time_text(lo)} … {time_text(hi)} ({hz_text(lo)} … {hz_text(hi)})"
        default = f"{time_text(d)} ({hz_text(d)})"
    elif key == "swing":
        rng = f"{lo / 10:.1f} … {hi / 10:.1f}"
        default = f"{d / 10:.1f}"
    elif key == "scale_root":
        rng = f"{NOTE_NAMES[lo]} … {NOTE_NAMES[hi]}"
        default = NOTE_NAMES[d]
    elif key == "repeats":
        rng = f"{lo} … {hi} (0 = ∞, forever)"
        default = "0 (∞)"
    elif typ == "uint32":
        rng = f"0 … {2**32 - 1:,}"
        default = f"{d:,}"
    else:
        signed = lo < 0
        rng = f"{num(lo, signed)} … {num(hi, signed)}"
        default = num(d, signed)
    return [_name(p), "Number", rng, default, unit, morph]


def _scale_group(group: list[dict], ui_scales: dict) -> list[str]:
    if len(group) != 12:
        raise SetupError(f"expected 12 scale-degree switches, found {len(group)}")
    first = group[0]["label"].split(" (")[0]
    last = group[-1]["label"].split(" (")[0].rsplit(" ", 1)[-1]
    on = [i for i, g in enumerate(group) if g["default"]]
    named = next((n for n, degs in ui_scales["scales"] if degs == on), None)
    default = "On at " + ", ".join(f"+{i}" for i in on) + (f": {named}" if named else "")
    return [f"**{first} … {last}**", "12 switches", "On, Off each; +n is n semitones above the root", default,
            "—", "Switches"]


def _chord_group(ons: list[dict], shifts: list[dict]) -> list[str]:
    if len(ons) != 6 or len(shifts) != 6:
        raise SetupError(f"expected 6 chord switch/interval pairs, found {len(ons)}/{len(shifts)}")
    a, b = shifts[0], shifts[-1]
    lo, hi = a["min"], a["max"]
    stem = re.sub(r"\s*\d+$", "", a["label"])                     # "Chord interval"
    last_n = re.search(r"(\d+)$", b["label"]).group(1)             # "6"
    first_n = re.search(r"(\d+)$", a["label"]).group(1)            # "1"
    on_first, on_last = ons[0]["label"], re.sub(r"^.*?(\d+ on)$", r"\1", ons[-1]["label"])
    name = f"**{stem} {first_n} \u2026 {last_n}**, with their switches **{on_first} \u2026 {on_last}**"
    # Compress equal neighbours: "4–6: 0, off".
    items = [(num(s["default"], True) if s["default"] else "0") + (", on" if o["default"] else ", off")
             for o, s in zip(ons, shifts)]
    parts, i = [], 0
    while i < len(items):
        j = i
        while j + 1 < len(items) and items[j + 1] == items[i]:
            j += 1
        parts.append((f"{i + 1}" if i == j else f"{i + 1}–{j + 1}") + f": {items[i]}")
        i = j + 1
    return [name, "6 pairs: switch and number", f"{num(lo, True)} … {num(hi, True)}", "; ".join(parts),
            _unit(a), "Switches"]


def render_table(params_doc: dict, bank_doc: dict) -> str:
    rates = params_doc["rate"]
    rows: list[list[str]] = []
    degs = [p for p in params_doc["params"] if re.fullmatch(r"scale_deg\d+", p["key"])]
    ons = [p for p in params_doc["params"] if re.fullmatch(r"chord_on\d+", p["key"])]
    shifts = [p for p in params_doc["params"] if re.fullmatch(r"chord_shift\d+", p["key"])]
    done_deg = done_chord = False
    for p in params_doc["params"]:
        k = p["key"]
        if k in {g["key"] for g in degs}:
            if not done_deg:
                rows.append(_scale_group(degs, params_doc["ui_scale_names"]))
                done_deg = True
        elif k in {g["key"] for g in ons + shifts}:
            if not done_chord:
                rows.append(_chord_group(ons, shifts))
                done_chord = True
        else:
            rows.append(_row(p, bank_doc, rates))
    head = ["Setting", "Control", "Range or choices", "Default", "Unit", "In a morph"]
    esc = lambda s: s.replace("|", "\\|")
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    lines += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def block(params_doc: dict, bank_doc: dict) -> str:
    return f"{STAMP}\n\n{render_table(params_doc, bank_doc)}"


# ---------------------------------------------------------------- the page

def split_page(text: str) -> tuple[str, str, str]:
    """(before BEGIN incl. marker, between markers, END marker onward)."""
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SetupError(f"the page must hold exactly one {BEGIN!r} and one {END!r}")
    b = text.index(BEGIN) + len(BEGIN)
    e = text.index(END)
    if e < b:
        raise SetupError("END marker before BEGIN marker")
    return text[:b], text[b:e], text[e:]


def table_problems(page: str, params_doc: dict, bank_doc: dict) -> list[str]:
    _, between, _ = split_page(page)
    want = block(params_doc, bank_doc).strip().splitlines()
    have = between.strip().splitlines()
    if want == have:
        return []
    diff = difflib.unified_diff(have, want, "page", "generator", lineterm="", n=1)
    return ["the page's settings table differs from the generator's output:", *diff]


def _strip_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.S)


def _fenceless_lines(text: str) -> list[str]:
    out, fenced = [], False
    for ln in text.splitlines():
        if ln.lstrip().startswith("```"):
            fenced = not fenced
            continue
        if not fenced:
            out.append(ln)
    return out


def figure_problems(page: str, figs: dict) -> list[str]:
    probs: list[str] = []
    entries = figs.get("entries")
    if not isinstance(entries, list):
        return ["figures.json has no `entries` list"]
    seen: dict[str, dict] = {}
    for n, e in enumerate(entries):
        missing = [f for f in FIELDS if f not in e]
        if missing:
            probs.append(f"entry {n} ({e.get('id', '?')}) is missing fields: {', '.join(missing)}")
            continue
        extra = [f for f in e if f not in FIELDS]
        if extra:
            probs.append(f"entry {e['id']} has unknown fields: {', '.join(extra)}")
        if e["id"] in seen:
            probs.append(f"duplicate id {e['id']}")
        seen[e["id"]] = e
        if not re.fullmatch(r"arp\.[a-z0-9][a-z0-9\-]*", e["id"]):
            probs.append(f"{e['id']}: ids are lower case and prefixed `arp.`")
        if e["chapter"] != "arp":
            probs.append(f"{e['id']}: chapter must be `arp`, found {e['chapter']!r}")
        if e["kind"] not in KINDS:
            probs.append(f"{e['id']}: unknown kind {e['kind']!r}")
        if e["status"] not in STATUSES:
            probs.append(f"{e['id']}: unknown status {e['status']!r}")
        if not isinstance(e["depends_on"], list) or not e["depends_on"]:
            probs.append(f"{e['id']}: depends_on must be a non-empty list")
        else:
            # horde's tools/manual_scaffold_check.py accepts only an H2-PLAN part id, a ROADMAP row (Bnnn) or an
            # ADR-nnn heading; SPEC and Arp decision references belong in `source`.
            for d in e["depends_on"]:
                if not (isinstance(d, str) and re.fullmatch(r"B\d+|ADR-\d+|[a-z][a-z0-9]*", d)):
                    probs.append(f"{e['id']}: depends_on {d!r} is not a horde part id, Bnnn row or ADR-nnn (put it in `source`)")
        if not isinstance(e["generated"], bool):
            probs.append(f"{e['id']}: generated must be true or false")
        for f in ("purpose", "content", "source"):
            if not isinstance(e[f], str) or not e[f].strip():
                probs.append(f"{e['id']}: {f} is empty")
    placed: dict[str, str] = {}
    for ln in _fenceless_lines(_strip_comments(page)):
        s = ln.strip()
        if s.startswith("[[") and not PLACEHOLDER.match(s):
            probs.append(f"malformed placeholder line: {s}")
            continue
        m = PLACEHOLDER.match(s)
        if not m:
            continue
        form, pid = m.groups()
        if pid in placed:
            probs.append(f"placeholder {pid} appears twice")
        placed[pid] = form
    for pid, form in placed.items():
        if pid not in seen:
            probs.append(f"placeholder {pid} has no entry in figures.json")
        elif seen[pid]["kind"] not in PLACEHOLDER_KINDS[form]:
            probs.append(f"{pid}: placeholder form {form} does not fit kind {seen[pid]['kind']!r}")
    for pid in seen:
        if pid not in placed:
            probs.append(f"entry {pid} has no placeholder on the page")
    return probs


STATUS = re.compile(r"^Status: (PENDING|READY-TO-WRITE) — \S.*$")


def status_problems(page: str) -> list[str]:
    """Every H2 and H3 carries exactly one status line (horde's README, "Status vocabulary")."""
    probs: list[str] = []
    cur, count = None, 0

    def close():
        if cur is not None and count != 1:
            probs.append(f"section {cur!r} has {count} status lines, not exactly 1")

    for ln in _fenceless_lines(_strip_comments(page)):
        if re.match(r"^#{2,3} ", ln):
            close()
            cur, count = ln, 0
        elif ln.startswith("Status:"):
            if not STATUS.match(ln):
                probs.append(f"malformed status line under {cur!r}: {ln}")
            count += 1
    close()
    return probs


# Outside HTML comments and Status lines, the prose is for musicians: no spec citations and no internal names.
LINT = [
    (re.compile(r"§|\bSPEC\b|params\.json|\bADR-\d"), "a spec or document citation (put it in an HTML comment)"),
    (re.compile(r"\b[a-z]+(?:_[a-z0-9]+)+\b"), "a snake_case internal name"),
    (re.compile(r"\b(?:NoteRef|kAbs|posNum|lastQ|epoch|gesture start|release-all)\b"), "an internal term"),
]


def prose_problems(page: str) -> list[str]:
    probs: list[str] = []
    for n, ln in enumerate(_fenceless_lines(_strip_comments(page)), 1):
        if ln.startswith("Status:"):
            continue
        for rx, what in LINT:
            m = rx.search(ln)
            if m:
                probs.append(f"prose has {what}: {m.group(0)!r} in: {ln.strip()[:90]}")
    return probs


# Numbers the prose states for a setting. A sentence that names a numeric setting in bold and says "default N" or
# "N to M" is held to params.json. Step fields (italics, not bold) and prose with no bold setting name are not
# checked, so a sentence naming two settings must give both the same numbers.
NUMERIC_TYPES = {"int", "percent", "permille", "uint32"}
NUM = r"[\u2212+-]?\d[\d,]*(?:\.\d+)?"
UNIT = r"(?:%|ms|s\b)?"
DEFAULT_RX = re.compile(rf"\bdefault(?:s)?(?:\s+to|\s+is)?\s+(?P<n>\d+/\d+T?|{NUM})\s*(?P<u>{UNIT})")
RANGE_RX = re.compile(rf"(?P<a>{NUM})\s*(?P<ua>{UNIT})\s+to\s+(?P<b>{NUM})\s*(?P<ub>{UNIT})")
BOLD = re.compile(r"\*\*([^*]+)\*\*")


def _val(text: str) -> float:
    return float(text.replace("\u2212", "-").replace(",", "").replace("+", ""))


def _scaled(key: str, v: float, unit: str) -> float:
    """The number in params.json's own unit (step_time_us in microseconds, swing in permille)."""
    if key == "step_time_us":
        return v * {"ms": 1e3, "s": 1e6}.get(unit, 1)
    if key == "swing" and unit == "%":
        return v * 10
    return v


def _bounds(p: dict) -> tuple[float, float]:
    if p["type"] == "uint32":
        return 0, 2**32 - 1
    return p["min"], p["max"]


def _prose_sentences(page: str):
    text = re.sub(r"%s.*?%s" % (re.escape(BEGIN), re.escape(END)), "", _strip_comments(page), flags=re.S)
    for ln in _fenceless_lines(text):
        if ln.startswith(("Status:", "|", "#")):
            continue
        for s in re.split(r"(?<=[.!?])\s+(?=[A-Z*`(\[])", ln):
            yield s


def number_problems(page: str, params_doc: dict, min_claims: int = 8) -> tuple[list[str], int]:
    numeric = {p["label"]: p for p in params_doc["params"] if p["type"] in NUMERIC_TYPES}
    rates = {r["name"] for r in params_doc["rate"]}
    rate_default = next(p["default"] for p in params_doc["params"] if p["key"] == "rate")
    probs: list[str] = []
    checked = 0
    for s in _prose_sentences(page):
        named = [b for b in BOLD.findall(s) if b in numeric or b == "Rate"]
        if not named:
            continue
        for m in DEFAULT_RX.finditer(s):
            for label in named:
                if label == "Rate":
                    ok = m.group("n") == rate_default and m.group("n") in rates
                    checked += 1
                    if not ok:
                        probs.append(f"prose says {label} defaults to {m.group('n')}, params.json says {rate_default}: {s.strip()[:80]}")
                    continue
                p = numeric[label]
                got = _scaled(p["key"], _val(m.group("n")), m.group("u"))
                checked += 1
                if got != p["default"]:
                    probs.append(f"prose says {label} defaults to {m.group('n')}{m.group('u')}, params.json says {p['default']}: {s.strip()[:80]}")
        for m in RANGE_RX.finditer(s):
            ua, ub = m.group("ua"), m.group("ub")
            ua = ua or ub
            for label in named:
                if label == "Rate":
                    continue
                p = numeric[label]
                lo, hi = _bounds(p)
                a, b = _scaled(p["key"], _val(m.group("a")), ua), _scaled(p["key"], _val(m.group("b")), ub)
                checked += 1
                if (a, b) != (lo, hi):
                    probs.append(f"prose says {label} runs {m.group('a')} to {m.group('b')}, params.json says {lo} to {hi}: {s.strip()[:80]}")
    if checked < min_claims:
        probs.append(f"the number check found only {checked} stated numbers to check (expected at least {min_claims}): "
                     "its patterns no longer match the prose")
    return probs, checked


# ---------------------------------------------------------------- driver

def load() -> tuple[dict, dict, dict, str]:
    try:
        params = json.loads(PARAMS.read_text(encoding="utf-8"))
        bank = json.loads(BANK.read_text(encoding="utf-8"))
        figs = json.loads(FIGURES.read_text(encoding="utf-8"))
        page = PAGE.read_text(encoding="utf-8")
    except (OSError, ValueError) as err:
        raise SetupError(str(err)) from err
    return params, bank, figs, page


def all_problems(params, bank, figs, page) -> dict[str, list[str]]:
    return {
        "table": table_problems(page, params, bank),
        "figures": figure_problems(page, figs),
        "status": status_problems(page),
        "prose": prose_problems(page),
        "numbers": number_problems(page, params)[0],
    }


def cmd_write() -> int:
    params, bank, _, page = load()
    head, _, tail = split_page(page)
    PAGE.write_text(f"{head}\n{block(params, bank)}\n{tail}", encoding="utf-8")
    print(f"wrote the settings table into {PAGE.relative_to(ROOT)}")
    return 0


def cmd_check() -> int:
    params, bank, figs, page = load()
    found = all_problems(params, bank, figs, page)
    red = False
    for name, probs in found.items():
        if name == "numbers" and not probs:
            print(f"PASS  numbers ({number_problems(page, params)[1]} stated numbers match params.json)")
        elif probs:
            red = True
            print(f"RED   {name}")
            for p in probs:
                print(f"      {p}")
        else:
            print(f"PASS  {name}")
    print("RED   the manual page is out of step" if red else "PASS  the manual page matches the spec")
    return 1 if red else 0


def cmd_plant() -> int:
    """One in-memory perturbation per detector. A detector that stays green on its plant cannot be trusted."""
    params, bank, figs, page = load()
    plants = {}

    p2 = copy.deepcopy(params)
    gate = next(p for p in p2["params"] if p["key"] == "gate")
    gate["default"] += 1                                    # one default off by one
    plants["table"] = ("table", (p2, bank, figs, page))

    f2 = copy.deepcopy(figs)
    f2["entries"].pop()                                     # a placeholder loses its entry
    plants["figures"] = ("figures", (params, bank, f2, page))

    s2 = re.sub(r"^Status: .*$", "", page, count=1, flags=re.M)   # a section loses its status line
    plants["status"] = ("status", (params, bank, figs, s2))

    l2 = page.replace(END, "Open the spec at §4.4 to see the formula.\n" + END, 1)   # a citation in prose
    plants["prose"] = ("prose", (params, bank, figs, l2))

    n2 = page.replace("1 to 200 %, default 80 %", "1 to 200 %, default 81 %", 1)    # a prose default off by one
    assert n2 != page, "plant text not found in the page: update the plant"
    plants["numbers (default)"] = ("numbers", (params, bank, figs, n2))
    n3 = page.replace("from \u221248 to +48 and defaults to +12", "from \u221248 to +36 and defaults to +12", 1)   # a prose range changed
    assert n3 != page, "plant text not found in the page: update the plant"
    plants["numbers (range)"] = ("numbers", (params, bank, figs, n3))

    d2 = copy.deepcopy(figs)
    d2["entries"][0]["depends_on"] = ["SPEC §4.2"]            # a depends_on horde's scaffold check would refuse
    plants["depends_on"] = ("figures", (params, bank, d2, page))

    missed = False
    for name, (which, args) in plants.items():
        probs = all_problems(*args)[which]
        if probs:
            print(f"RED   plant '{name}': detected ({probs[0]})")
        else:
            missed = True
            print(f"GREEN plant '{name}': NOT detected, the {which} check cannot be trusted")
    if missed:
        return 2
    print("every plant was detected")
    return 3


def main(argv: list[str]) -> int:
    modes = {"--write": cmd_write, "--check": cmd_check, "--plant": cmd_plant}
    if len(argv) != 2 or argv[1] not in modes:
        print(__doc__)
        return 2
    try:
        return modes[argv[1]]()
    except SetupError as err:
        print(f"SETUP ERROR: {err}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
